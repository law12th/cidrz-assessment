/**
 * A correlation ID for each request, so a clinic can quote it and support can find the server log line.
 * crypto.randomUUID is missing from older browsers on some clinic PCs, so there are fallbacks.
 */
export function newCorrelationId(): string {
  const cryptoApi: Crypto | undefined = typeof crypto === 'undefined' ? undefined : crypto;
  if (cryptoApi && typeof cryptoApi.randomUUID === 'function') {
    return cryptoApi.randomUUID();
  }
  const bytes = new Uint8Array(16);
  if (cryptoApi && typeof cryptoApi.getRandomValues === 'function') {
    cryptoApi.getRandomValues(bytes);
  } else {
    for (let i = 0; i < bytes.length; i++) bytes[i] = Math.floor(Math.random() * 256);
  }
  const hex = Array.from(bytes, (b) => b.toString(16).padStart(2, '0')).join('');
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20)}`;
}
